<?php

require_once __DIR__ . '/../AI/AiClient.php';
require_once __DIR__ . '/../Db/Database.php';

class OutreachService
{
    private PDO $db;
    private AiClient $aiClient;

    public function __construct()
    {
        $this->db = Database::getConnection();
        $this->aiClient = new AiClient();
    }

    public function generateMessage(int $leadId, string $tone, array $auditFindings): ?string
    {
        $systemPrompt = 'You are an AI outreach assistant. Create a personalized outreach message grounded in audit findings. Avoid spammy language, fake compliments, and generic templates. Output only valid JSON.';
        $userPrompt = 'Create one outreach message in the selected tone. Reference specific audit findings with evidence, not vague praise. The lead owner will copy/send manually. Do not claim to have already reviewed the site beyond the findings.';
        $instructions = [
            'Return JSON with a single key: message.',
            'Tone must be one of formal, casual, or friendly.',
            'Include at least one specific issue or opportunity from the audit findings.',
            'Do not mention that this is generated by AI.',
        ];

        $inspection = json_encode($auditFindings, JSON_UNESCAPED_UNICODE);
        $raw = $this->aiClient->generateStructuredJson((string)$leadId, $systemPrompt, $userPrompt . "\nTone: $tone\nAudit findings:\n" . $inspection, $instructions);
        if ($raw === null || empty($raw['message'])) {
            return null;
        }

        $message = trim($raw['message']);
        $this->saveMessage($leadId, $tone, $message);
        return $message;
    }

    public function saveMessage(int $leadId, string $tone, string $message): void
    {
        $driver = $this->db->getAttribute(PDO::ATTR_DRIVER_NAME);
        if ($driver === 'sqlite') {
            $sql = 'INSERT INTO outreach_messages (lead_id, tone, message, status) VALUES (:lead_id, :tone, :message, :status) ON CONFLICT(lead_id) DO UPDATE SET tone = :tone_u, message = :message_u, status = :status_u, updated_at = CURRENT_TIMESTAMP';
        } else {
            $sql = 'INSERT INTO outreach_messages (lead_id, tone, message, status) VALUES (:lead_id, :tone, :message, :status) ON DUPLICATE KEY UPDATE tone = :tone_u, message = :message_u, status = :status_u, updated_at = CURRENT_TIMESTAMP';
        }
        $statement = $this->db->prepare($sql);
        $statement->execute([
            ':lead_id' => $leadId,
            ':tone' => $tone,
            ':message' => $message,
            ':status' => 'AI Generated',
            ':tone_u' => $tone,
            ':message_u' => $message,
            ':status_u' => 'AI Generated',
        ]);
    }

    public function getByLeadId(int $leadId): ?array
    {
        $statement = $this->db->prepare('SELECT * FROM outreach_messages WHERE lead_id = :lead_id');
        $statement->execute([':lead_id' => $leadId]);
        $message = $statement->fetch();
        return $message ?: null;
    }

    public function updateMessage(int $leadId, string $message, string $status): bool
    {
        $statement = $this->db->prepare('UPDATE outreach_messages SET message = :message, status = :status WHERE lead_id = :lead_id');
        return $statement->execute([':message' => $message, ':status' => $status, ':lead_id' => $leadId]);
    }
}
